def ev_text(lang: str, key: str, **kwargs) -> str:
    lang_key = lang if lang in EVENT_STRINGS else ("hi" if lang == "hi" else "en")
    template = EVENT_STRINGS.get(lang_key, EVENT_STRINGS["en"]).get(key, EVENT_STRINGS["en"].get(key, ""))
    return template.format(**kwargs) if kwargs else template

